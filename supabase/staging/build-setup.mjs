// Build a staging-only setup from the supplied metadata and reviewed migrations.
// Does not connect to Supabase or copy production user/catalog records.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const audit = JSON.parse(await readFile(process.argv[2] ?? new URL('../../security-audit.json', import.meta.url), 'utf8'));
const quote = value => `"${value.replaceAll('"', '""')}"`;
const owned = ['profiles', 'Scan-profiles', 'cart_items', 'saved_products'];
const types = new Set(['uuid', 'text', 'character varying', 'date', 'boolean', 'smallint', 'integer', 'timestamp with time zone']);
const parts = [`-- STAGING ONLY: https://supabase.com/dashboard/project/tkljmhlrmutcsciqimlq
-- Generated by build-setup.mjs from audited metadata and the named migrations.
-- Run the ENTIRE file in SQL Editor as postgres. All setup is one transaction.
-- Creates no Auth users and copies no production user records.
-- Synthetic catalog rows are for security tests, not real recommendations.
-- Not a production migration and not a full production schema/trigger clone.
begin;
do $staging_guard$
begin
  if to_regclass('public.profiles') is not null
     or to_regclass('public."Scan-profiles"') is not null
     or to_regclass('public.cart_items') is not null
     or to_regclass('public.saved_products') is not null
     or to_regclass('public.products') is not null
     or to_regclass('public.hairstyles') is not null
     or to_regclass('private.api_requests') is not null
     or exists (select 1 from storage.buckets) then
    raise exception 'Staging setup requires an unused project. Existing app tables or storage buckets found; no setup changes applied.';
  end if;
end
$staging_guard$;

-- Minimal synthetic catalogs; their full production definitions were not audited.
create table public.products (
  "No" smallint primary key, product_id text not null, product_name text not null,
  price_lkr numeric, description text, image_url text, brand_name text, category text
);
insert into public.products("No", product_id, product_name, price_lkr, description)
values (1, 'STAGING-TEST-ONLY', 'Staging test product', 100, 'Synthetic security-test fixture; not a real product or recommendation.');
create table public.hairstyles (
  id integer primary key, hairstyle_name text, face_shape text,
  gender text, hair_length text, image_url text
);
insert into public.hairstyles(id, hairstyle_name, face_shape, gender, hair_length)
values (1, 'Staging test hairstyle', 'oval', 'female', 'medium');
alter table public.products enable row level security;
alter table public.hairstyles enable row level security;
`];
for (const table of owned) {
  const columns = audit.columns.filter(column => column.table_name === table);
  if (!columns.length) throw new Error(`Missing audited table: ${table}`);
  const definitions = columns.map(column => {
    if (!types.has(column.data_type) || column.is_identity !== 'NO' || column.is_generated !== 'NEVER') {
      throw new Error(`Review unsupported column metadata: ${table}.${column.column_name}`);
    }
    if (column.column_default !== null && !['gen_random_uuid()', 'now()', 'false', '1'].includes(column.column_default)) {
      throw new Error(`Review unsupported default: ${table}.${column.column_name}`);
    }
    return `  ${quote(column.column_name)} ${column.data_type}` +
      (column.is_nullable === 'NO' ? ' not null' : '') +
      (column.column_default === null ? '' : ` default ${column.column_default}`);
  });
  parts.push(`create table public.${quote(table)} (\n${definitions.join(',\n')}\n);`);
}
const constraints = [...audit.constraints].sort((a, b) =>
  Number(a.definition.startsWith('FOREIGN KEY')) - Number(b.definition.startsWith('FOREIGN KEY')));
for (const item of constraints) {
  if (!owned.includes(item.table_name)) throw new Error('Unexpected audited constraint table');
  parts.push(`alter table public.${quote(item.table_name)} add constraint ${quote(item.conname)} ${item.definition};`);
}
for (const table of owned) parts.push(`alter table public.${quote(table)} enable row level security;`);
parts.push(`insert into storage.buckets(id, name, public, file_size_limit, allowed_mime_types)
values ('profile-images', 'profile-images', false, 5242880, array['image/jpeg','image/png','image/webp']);`);
for (const item of audit.policies) {
  if (!(['public', 'storage'].includes(item.schemaname)) ||
      !([...owned, 'products', 'hairstyles', 'objects'].includes(item.tablename))) throw new Error('Unexpected policy target');
  parts.push(`create policy ${quote(item.policyname)} on ${quote(item.schemaname)}.${quote(item.tablename)}` +
    ` as ${item.permissive} for ${item.cmd} to ${item.roles.map(quote).join(',')}` +
    (item.qual === null ? '' : ` using (${item.qual})`) +
    (item.with_check === null ? '' : ` with check (${item.with_check})`) + ';');
}
// Reproduce only public-table client grants. Hosted Storage's shared grants
// stay managed by Supabase; the four bucket policies enforce photo ownership.
for (const item of audit.grants.filter(item => item.table_schema === 'public')) {
  parts.push(`grant ${item.privilege_type} on public.${quote(item.table_name)} to ${quote(item.grantee)};`);
}
const migrations = [
  '20260911020000_harden_products_privileges.sql',
  '20260915000000_add_env_to_profiles.sql',
  '20261031000000_user_data_security.sql',
  '20261031010000_api_quotas.sql',
  '20261031020000_account_deletion.sql',
];
for (const name of migrations) {
  const source = await readFile(new URL(`../migrations/${name}`, import.meta.url), 'utf8');
  parts.push(`\n-- Source: ${name}\n-- SHA-256: ${createHash('sha256').update(source).digest('hex')}\n` +
    source.replace(/^\s*(?:begin|commit);[\t ]*\r?$/gmi, ''));
}
parts.push(`commit;\nselect 'staging_setup_complete' as result;\n`);
const output = new URL('./setup.sql', import.meta.url);
await writeFile(output, parts.join('\n\n'), 'utf8');
console.log(`Prepared ${fileURLToPath(output)}`);
